#!/usr/bin/env node
// review-metrics.mjs: the five review signals and four thresholds of the two-tier review
// (docs/process/review-metrics.md). Plain Node, no dependencies.
//
//   node tools/review-metrics.mjs [--now <ISO date>] [--repos a,b,...] [--json] [--create]
//                                 [--fixtures <file.json>]
//
// Reads, over the four weeks before --now (default: now):
//   - merged pull requests of every project in repos.json and of statewalker-root (--repos narrows);
//   - their gate record lines, `<!-- gate: pass=<n> critical=<n> downgraded=<n> high=<n> rejected=<n> -->`;
//   - deferred bugs (issues labelled bug + review-followup or health-review) per project;
//   - escalated bug tickets (open root issues labelled bug) and open area:root issues (duplicate check).
// Prints a Markdown report (the weekly "Review health" comment) or, with --json, the same as JSON.
// Each firing threshold is a root ticket to create; dry run unless --create, and never when an
// open area:root issue already has the same title.
// GitHub is read with `gh api` (REST); --fixtures reads recorded responses instead (tests).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { fixtureSource, liveSource } from "./lib/github.mjs";
import { isoWeek } from "./lib/week.mjs";

const ORG = "statewalker";
const SELF = "statewalker-root";
const DAY = 86400000;
const WEEKS = 4;
const RECORD = /^<!--\s*gate:\s*pass=(\d+)\s+critical=(\d+)\s+downgraded=(\d+)\s+high=(\d+)\s+rejected=(\d+)\s*-->$/;
const LABELS = ["area:root", "needs-triage"];

// ---- arguments ----

function parseArgs(argv) {
  const a = { now: new Date(), repos: null, json: false, create: false, fixtures: null };
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i];
    if (k === "--now") a.now = new Date(argv[++i]);
    else if (k === "--repos") a.repos = argv[++i].split(",").filter(Boolean);
    else if (k === "--json") a.json = true;
    else if (k === "--create") a.create = true;
    else if (k === "--fixtures") a.fixtures = argv[++i];
    else throw new Error(`unknown argument ${k}`);
  }
  if (Number.isNaN(a.now.getTime())) throw new Error("--now is not a date");
  if (a.create && a.fixtures) throw new Error("--create cannot be used with --fixtures");
  return a;
}

// ---- reading ----

/**
 * Whether a record has a table row whose Outcome is "overridden" (merging.md, "Record of a pass":
 * columns #, Proposed / judged, Verdict, Outcome). The Outcome is everything after the third cell,
 * so a pipe in the quoted human message does not hide it; the word in prose or in the Verdict
 * cell is not an override.
 */
export function hasOverrideRow(body) {
  for (const line of (body ?? "").split(/\r?\n/)) {
    if (!/^\s*\|/.test(line)) continue;
    const cells = line.trim().replace(/^\|/, "").replace(/\|$/, "").split(/(?<!\\)\|/);
    if (cells.length < 4) continue;
    const outcome = cells.slice(3).join("|").replace(/[*_`]/g, "").trim();
    if (/^overridden\b/i.test(outcome)) return true;
  }
  return false;
}

/** The gate records of one pull request's comments: { records, malformed }. */
export function gateRecords(comments) {
  const records = [];
  let malformed = 0;
  for (const c of comments) {
    // The record line ends the comment, but tooling may append a footer after it
    // ("Generated by …"): take the last gate line wherever it is.
    const gateLines = (c.body ?? "").split(/\r?\n/).map((l) => l.trim()).filter((l) => l.startsWith("<!--") && /gate:/.test(l));
    const m = gateLines.length ? RECORD.exec(gateLines[gateLines.length - 1]) : null;
    if (m) {
      const [pass, critical, downgraded, high, rejected] = m.slice(1).map(Number);
      const override = hasOverrideRow(c.body);
      records.push({ pass, critical, downgraded, high, rejected, override });
    } else if (/<!--\s*gate:/.test(c.body ?? "")) malformed++;
  }
  return { records, malformed };
}

function read(src, repos, now) {
  const start = new Date(now.getTime() - WEEKS * 7 * DAY);
  const prs = [];
  const deferred = {};
  const skipped = [];
  for (const repo of repos) {
    try {
      readRepo(repo);
    } catch (e) {
      if (!e.unreadable) throw e; // a missing fixture is a test error, never a skip
      skipped.push({ repo, reason: e.message });
      prs.splice(0, prs.length, ...prs.filter((p) => p.repo !== repo));
      delete deferred[repo];
    }
  }
  function readRepo(repo) {
    const closed = src.list(`repos/${ORG}/${repo}/pulls?state=closed&sort=updated&direction=desc`, (p) => new Date(p.updated_at) < start);
    for (const p of closed) {
      if (!p.merged_at) continue;
      const merged = new Date(p.merged_at);
      if (merged < start || merged > now) continue;
      const comments = src.list(`repos/${ORG}/${repo}/issues/${p.number}/comments`);
      prs.push({ repo, number: p.number, title: p.title, created: new Date(p.created_at), merged, ...gateRecords(comments) });
    }
    const bugs = new Map();
    for (const label of ["review-followup", "health-review"]) {
      for (const i of src.list(`repos/${ORG}/${repo}/issues?state=all&labels=bug,${label}`)) {
        if (!i.pull_request) bugs.set(i.number, { number: i.number, created: new Date(i.created_at), closed: i.closed_at ? new Date(i.closed_at) : null });
      }
    }
    deferred[repo] = [...bugs.values()];
  }
  const rootOpen = (labels) => src.list(`repos/${ORG}/${SELF}/issues?state=open&labels=${labels}`).filter((i) => !i.pull_request);
  // Escalated bug tickets (docs/process/prevention.md): ready-for-agent bugs, not deferred bugs themselves.
  const deferredLabel = (i) => (i.labels ?? []).some((l) => ["review-followup", "health-review"].includes(l.name ?? l));
  const escalations = rootOpen("bug,ready-for-agent").filter((i) => !deferredLabel(i)).length;
  return { prs, deferred, skipped, escalations, rootIssues: rootOpen("area:root") };
}

// ---- computing ----

const median = (xs) => {
  if (!xs.length) return null;
  const s = [...xs].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const round = (x, d = 2) => (x == null ? null : Math.round(x * 10 ** d) / 10 ** d);
const sum = (xs, f) => xs.reduce((n, x) => n + f(x), 0);
/** Week index of a date: 0 = the latest seven days before now, 3 = the oldest in the window. */
const weekOf = (d, now) => Math.floor((now - d) / (7 * DAY));

export function compute({ prs, deferred, skipped = [], escalations, rootIssues }, now) {
  const recorded = prs.filter((p) => p.records.length);
  const total = (p, k) => sum(p.records, (r) => r[k]);
  const passes = recorded.map((p) => Math.max(...p.records.map((r) => r.pass)));
  // An override: a record row's Outcome is "overridden" (merging.md, "Record of a pass"). A critical count alone
  // does not tell, since it counts real critical findings whether fixed or not.
  const overridden = (p) => p.records.some((r) => r.override);
  const critical = sum(recorded, (p) => total(p, "critical"));
  const findings = sum(recorded, (p) => total(p, "critical") + total(p, "high") + total(p, "rejected"));
  const rejected = sum(recorded, (p) => total(p, "rejected"));

  const repos = Object.keys(deferred);
  const perProject = {};
  for (const repo of repos) {
    const mine = recorded.filter((p) => p.repo === repo);
    const half = (early) => mine.filter((p) => (weekOf(p.merged, now) >= 2) === early);
    const rate = (xs) => (xs.length ? sum(xs, (p) => total(p, "critical")) / xs.length : null);
    // Open deferred bugs at the end of each of the last four weeks, oldest first.
    const openAt = (t) => deferred[repo].filter((b) => b.created <= t && (!b.closed || b.closed > t)).length;
    const history = [3, 2, 1, 0].map((k) => openAt(new Date(now.getTime() - k * 7 * DAY)));
    perProject[repo] = {
      merged: prs.filter((p) => p.repo === repo).length,
      criticalPerMerge: round(rate(mine)),
      criticalPerMergeEarlier: round(rate(half(true))),
      criticalPerMergeLater: round(rate(half(false))),
      deferredBugs: history[3],
      deferredHistory: history,
    };
  }

  const signals = {
    merged: prs.length,
    withRecord: recorded.length,
    withoutRecord: prs.filter((p) => !p.records.length).map((p) => `${p.repo}#${p.number}`),
    malformedRecords: sum(prs, (p) => p.malformed),
    skippedRepos: skipped,
    passes: { median: median(passes), max: passes.length ? Math.max(...passes) : null },
    critical: { total: critical, perMerge: round(recorded.length ? critical / recorded.length : null), downgraded: sum(recorded, (p) => total(p, "downgraded")), overrides: recorded.filter(overridden).length },
    speculative: { rejected, findings, share: round(findings ? rejected / findings : null) },
    deferredBugs: Object.fromEntries(repos.map((r) => [r, perProject[r].deferredBugs])),
    escalations,
    timeToMergeHours: { median: round(median(prs.map((p) => (p.merged - p.created) / 3600000)), 1) },
  };

  const thresholds = [];
  const fire = (title, value, action) => thresholds.push({ title, value, action });
  if (signals.passes.median != null && signals.passes.median > 1.5)
    fire("Review metrics: median gate passes above 1.5", `median ${signals.passes.median} passes over ${recorded.length} pull requests`, "Tighten the review rubric or the reviewer brief so that critical findings are found and fixed in one pass.");
  if (signals.speculative.share != null && signals.speculative.share > 0.3)
    fire("Review metrics: speculative share above 30%", `${rejected} of ${findings} findings rejected as speculative (${Math.round(signals.speculative.share * 100)}%)`, "Recalibrate the reviewer: add contrasting calibration examples to the review rubric.");
  for (const repo of repos) {
    const p = perProject[repo];
    if (p.criticalPerMergeEarlier != null && p.criticalPerMergeLater != null && p.criticalPerMergeLater > p.criticalPerMergeEarlier)
      fire(`Review metrics: critical findings rising in ${repo}`, `critical findings per merge ${p.criticalPerMergeEarlier} → ${p.criticalPerMergeLater} (weeks 3–4 → 1–2 before now)`, `Open a prevention (\`ci-baseline\`) ticket in ${repo} for the class the critical findings fall into.`);
    const h = p.deferredHistory;
    if (h[0] < h[1] && h[1] < h[2] && h[2] < h[3])
      fire(`Review metrics: deferred bugs growing in ${repo}`, `open deferred bugs ${h.join(" → ")} over the last three weeks`, `Give ${repo} extra health-review slots until its deferred bugs stop growing.`);
  }
  for (const t of thresholds) t.duplicateOf = rootIssues.find((i) => i.title === t.title)?.number ?? null;

  // Calibration candidates: this week's downgrades and overrides (docs/process/review-metrics.md).
  const calibration = recorded
    .filter((p) => weekOf(p.merged, now) === 0 && (total(p, "downgraded") > 0 || overridden(p)))
    .map((p) => ({ pr: `${p.repo}#${p.number}`, downgraded: total(p, "downgraded"), override: overridden(p) }));

  return { now: now.toISOString(), window: { weeks: WEEKS }, signals, perProject, thresholds, calibration };
}

// ---- output ----

function markdown(r) {
  const s = r.signals;
  const v = (x, unit = "") => (x == null ? "n/a" : `${x}${unit}`);
  const lines = [
    `## Review metrics, four weeks to ${r.now.slice(0, 10)}`,
    "",
    "| Signal | Value |",
    "|---|---|",
    `| Gate passes per pull request | median ${v(s.passes.median)}, max ${v(s.passes.max)} (${s.withRecord} of ${s.merged} merged pull requests have a record) |`,
    `| Critical findings per merge | ${v(s.critical.perMerge)} (${s.critical.total} critical, ${s.critical.downgraded} downgraded, overrides: ${s.critical.overrides}) |`,
    `| Rejected as speculative | ${s.speculative.share == null ? "n/a" : `${Math.round(s.speculative.share * 100)}%`} (${s.speculative.rejected} of ${s.speculative.findings}) |`,
    `| Open deferred bugs | ${Object.entries(s.deferredBugs).filter(([, n]) => n).map(([k, n]) => `${k} ${n}`).join(", ") || "none"}; escalated: ${s.escalations} |`,
    `| Time to merge | median ${v(s.timeToMergeHours.median, " h")} |`,
    "",
  ];
  if (s.skippedRepos.length)
    lines.push(`Not readable, skipped: ${s.skippedRepos.map((x) => x.repo).join(", ")}.`, "");
  if (s.withoutRecord.length || s.malformedRecords)
    lines.push(`Missing gate records: ${s.withoutRecord.length}${s.withoutRecord.length ? ` (${s.withoutRecord.slice(0, 10).join(", ")}${s.withoutRecord.length > 10 ? ", …" : ""})` : ""}; malformed record lines: ${s.malformedRecords}.`, "");
  lines.push(r.thresholds.length ? "**Thresholds firing:**" : "No threshold fires.");
  for (const t of r.thresholds) lines.push(`- ${t.title}: ${t.value}. ${t.duplicateOf ? `Already filed: #${t.duplicateOf}.` : t.created ? `Filed: #${t.created}.` : "To file."}`);
  if (r.calibration.length) {
    lines.push("", "**Calibration candidates** (this week's downgrades and overrides):");
    for (const c of r.calibration) lines.push(`- ${c.pr}: ${c.downgraded} downgraded${c.override ? ", override" : ""}`);
  }
  // The weekly routine posts this report on #36; the marker tells a rerun the week's metrics are in.
  lines.push("", `<!-- review-metrics: week=${isoWeek(new Date(r.now))} -->`);
  return lines.join("\n");
}

function ticketBody(t, r) {
  return [
    `The weekly review metrics (four weeks to ${r.now.slice(0, 10)}) crossed a threshold (\`docs/process/review-metrics.md\`).`,
    "",
    `- **Signal**: ${t.value}.`,
    `- **Action**: ${t.action}`,
    "",
    "_Opened by `tools/review-metrics.mjs --create`._",
  ].join("\n");
}

// ---- main ----

export function main(argv) {
  const args = parseArgs(argv);
  const src = args.fixtures ? fixtureSource(args.fixtures) : liveSource();
  const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const repos = args.repos ?? [...Object.keys(JSON.parse(fs.readFileSync(path.join(here, "repos.json"), "utf8"))), SELF];
  const report = compute(read(src, repos, args.now), args.now);
  if (args.create) {
    for (const t of report.thresholds.filter((x) => !x.duplicateOf)) {
      t.created = src.create(`repos/${ORG}/${SELF}/issues`, { title: t.title, body: ticketBody(t, report), labels: LABELS }).number;
    }
  }
  return args.json ? JSON.stringify(report, null, 2) : markdown(report);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    console.log(main(process.argv.slice(2)));
  } catch (e) {
    console.error(`review-metrics: ${e.message}`);
    process.exit(1);
  }
}
