#!/usr/bin/env node
// rename-package.mjs REPO OLD=NEW [OLD=NEW ...]
//
// Renames @statewalker packages inside one repository:
//   - a package that LIVES in REPO (packages/<dir> or apps/<dir> whose package.json has the old
//     name) gets its directory moved with `git mv` (to the new name's short form, when the
//     directory was named after the old one) and its `name` changed;
//   - every tracked text file (sources, manifests, catalogs, tsconfig paths, READMEs) has
//     whole-name occurrences of `@statewalker/OLD` replaced by `@statewalker/NEW`. A name is whole
//     when the next character is not a word character, `.` or `-` (so renaming `storage` leaves
//     `storage-utils` alone). Subpaths (`@statewalker/OLD/x`) are renamed with their package.
//   - lockfiles and CHANGELOGs are left alone: the lockfile is regenerated by `pnpm install`, a
//     changelog is history.
// Prints what changed. Run `pnpm install` afterwards.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const [repo, ...pairs] = process.argv.slice(2);
if (!repo || pairs.length === 0) {
  console.error("usage: rename-package.mjs REPO OLD=NEW [OLD=NEW ...]");
  process.exit(2);
}
const renames = pairs.map((p) => {
  const [from, to] = p.split("=");
  if (!from || !to) throw new Error(`bad pair: ${p}`);
  return { from: `@statewalker/${from}`, to: `@statewalker/${to}`, fromShort: from, toShort: to };
});
const git = (...args) => execFileSync("git", ["-C", repo, ...args], { encoding: "utf8" });
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// 1. Move the packages that live here.
const local = new Set(); // renames whose package lives in REPO
for (const r of renames) {
  for (const root of ["packages", "apps"]) {
    const dir = path.join(repo, root);
    if (!fs.existsSync(dir)) continue;
    for (const entry of fs.readdirSync(dir)) {
      const manifest = path.join(dir, entry, "package.json");
      if (!fs.existsSync(manifest)) continue;
      if (JSON.parse(fs.readFileSync(manifest, "utf8")).name !== r.from) continue;
      local.add(r.from);
      if (entry === r.fromShort) {
        git("mv", path.join(root, entry), path.join(root, r.toShort));
        console.log(`moved ${root}/${entry} -> ${root}/${r.toShort}`);
      } else {
        console.log(`kept directory ${root}/${entry} (not named after ${r.fromShort})`);
      }
    }
  }
}

// 2. Replace whole names in every tracked text file.
const patterns = renames.map((r) => ({
  re: new RegExp(`${escape(r.from)}(?![\\w.-])`, "g"),
  to: r.to,
  // a package's own directory in repository.directory / docs paths
  dirRe: new RegExp(`(packages|apps)/${escape(r.fromShort)}(?![\\w.-])`, "g"),
  dirTo: `$1/${r.toShort}`,
  // a sibling package's directory, e.g. a vitest alias to "../<dir>/src/index.ts". Only for a
  // package that lives in REPO: elsewhere `../storage/` is as likely a module's own folder.
  siblingRe: local.has(r.from)
    ? new RegExp(`(\\.\\./)${escape(r.fromShort)}(?=[/"'])`, "g")
    : /$^/g,
  siblingTo: `$1${r.toShort}`,
}));
const files = git("ls-files").split("\n").filter(Boolean);
let changed = 0;
for (const f of files) {
  const base = path.basename(f);
  if (base === "pnpm-lock.yaml" || /^CHANGELOG/i.test(base)) continue;
  const full = path.join(repo, f);
  let text;
  try {
    const buf = fs.readFileSync(full);
    if (buf.includes(0)) continue; // binary
    text = buf.toString("utf8");
  } catch {
    continue;
  }
  let next = text;
  for (const p of patterns)
    next = next.replace(p.re, p.to).replace(p.dirRe, p.dirTo).replace(p.siblingRe, p.siblingTo);
  if (next !== text) {
    fs.writeFileSync(full, next);
    changed++;
    console.log(`edited ${f}`);
  }
}
console.log(`${changed} files edited`);
